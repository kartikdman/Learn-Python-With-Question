# Adding two pre defined numbers

a = int(input("Enter your first number: ")) # Our First Number that is saved into variable "a"
b = int(input("Enter your second number: ")) # Our Second Number that is saved into variable "b"

# Let's Print the sum of both numbers

print("The sum of given two numbers is ", a + b)


